const TABELAS = [
    {
        nome: "tb_questoes",
        sql: `CREATE TABLE IF NOT EXISTS public.tb_questoes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            atividade_id BIGINT NOT NULL REFERENCES public.tb_atividades(id) ON DELETE CASCADE,
            ordem INTEGER NOT NULL,
            tipo VARCHAR(20) NOT NULL,
            enunciado TEXT NOT NULL,
            pontos NUMERIC(7,2) NOT NULL DEFAULT 1.00,
            alternativas TEXT,
            correta INTEGER,
            CONSTRAINT uq_tb_questoes_atividade_ordem UNIQUE (atividade_id, ordem)
        )`
    },
    {
        nome: "tb_respostas",
        sql: `CREATE TABLE IF NOT EXISTS public.tb_respostas (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            entrega_id BIGINT NOT NULL REFERENCES public.tb_entregas(id) ON DELETE CASCADE,
            questao_id BIGINT NOT NULL REFERENCES public.tb_questoes(id) ON DELETE CASCADE,
            resposta TEXT,
            alternativa INTEGER,
            pontos NUMERIC(7,2),
            comentario TEXT,
            CONSTRAINT uq_tb_respostas_entrega_questao UNIQUE (entrega_id, questao_id)
        )`
    },
    {
        nome: "tb_inicios",
        sql: `CREATE TABLE IF NOT EXISTS public.tb_inicios (
            atividade_id BIGINT NOT NULL REFERENCES public.tb_atividades(id) ON DELETE CASCADE,
            aluno_id BIGINT NOT NULL REFERENCES public.tb_usuarios(id) ON DELETE CASCADE,
            iniciada_ms BIGINT NOT NULL,
            PRIMARY KEY (atividade_id, aluno_id)
        )`
    }
];

const INDICES = [
    "CREATE INDEX IF NOT EXISTS idx_tb_respostas_questao ON public.tb_respostas (questao_id)"
];

const COLUNAS = [
    { tabela: "tb_atividades", coluna: "tempo_limite_min", definicao: "INTEGER" },
    { tabela: "tb_atividades", coluna: "avaliativa", definicao: "BOOLEAN NOT NULL DEFAULT FALSE" },
    { tabela: "tb_atividades", coluna: "aplicada", definicao: "BOOLEAN NOT NULL DEFAULT FALSE" }
];

const MAX_TENTATIVAS = 5;
const NOVA_TENTATIVA_MS = 30 * 1000;

async function aplicar(pool) {
    const problemas = [];

    for (const tabela of TABELAS) {
        try {
            await pool.execute(tabela.sql);
        } catch (erro) {
            problemas.push(`${tabela.nome}: ${erro.message}`);
        }
    }

    for (const indice of INDICES) {
        try {
            await pool.execute(indice);
        } catch (erro) {
            problemas.push(`índice de questões: ${erro.message}`);
        }
    }

    for (const coluna of COLUNAS) {
        try {
            const [linhas] = await pool.execute(
                `SELECT COUNT(*) AS n FROM information_schema.columns
                 WHERE table_schema = 'public' AND table_name = ? AND column_name = ?`,
                [coluna.tabela, coluna.coluna]
            );
            if (Number(linhas[0].n) === 0) {
                await pool.execute(
                    `ALTER TABLE public.${coluna.tabela} ADD COLUMN ${coluna.coluna} ${coluna.definicao}`
                );
                console.log(`[esquema] coluna ${coluna.tabela}.${coluna.coluna} criada.`);
            }
        } catch (erro) {
            problemas.push(`${coluna.tabela}.${coluna.coluna}: ${erro.message}`);
        }
    }

    return problemas;
}

async function garantirEsquema(pool, tentativa = 1) {
    let problemas;
    try {
        problemas = await aplicar(pool);
    } catch (erro) {
        problemas = [erro.message];
    }

    if (problemas.length === 0) {
        console.log("[esquema] tabelas de questões conferidas.");
        return;
    }

    const conexaoCaida = problemas.some((problema) =>
        /ECONNREFUSED|ETIMEDOUT|ENOTFOUND|ECONNRESET|^08|28P01/i.test(problema)
    );
    if (conexaoCaida && tentativa < MAX_TENTATIVAS) {
        console.warn(`[esquema] banco indisponível (tentativa ${tentativa}/${MAX_TENTATIVAS}); tentando de novo em 30s.`);
        const timer = setTimeout(() => garantirEsquema(pool, tentativa + 1), NOVA_TENTATIVA_MS);
        if (timer.unref) timer.unref();
        return;
    }

    console.warn("[esquema] não foi possível preparar o banco para as questões:");
    problemas.forEach((problema) => console.warn("  - " + problema));
    console.warn("[esquema] Verifique as permissões e execute o esquema PostgreSQL do projeto.");
}

module.exports = { garantirEsquema, TABELAS, COLUNAS };
